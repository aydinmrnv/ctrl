@_exported import CtrlCore

/// Canonical format strings from `ctrl-core` (`core/src/formats.rs`).
public enum Format {
    public static let plainText = "text/plain"
    public static let html = "text/html"
    public static let rtf = "text/rtf"
    public static let png = "image/png"
    public static let tiff = "image/tiff"
    public static let jpeg = "image/jpeg"
    public static let url = "text/uri-list"
    public static let fileURL = "public.file-url"
    public static let fileList = "x-ctrl/file-list"
    public static let color = "x-ctrl/color"

    public static let images: Set<String> = [png, tiff, jpeg]
}

/// Pasteboard types Ctrl reads or writes itself.
public enum PasteboardMarker {
    /// Written next to every clip Ctrl puts on the pasteboard. Its value is the
    /// device the clip came from. The watcher never sends an item carrying it,
    /// so a received clip doesn't travel back to its origin.
    public static let origin = "app.ctrl.origin"

    /// nspasteboard.org markers. An item carrying any of them is never sent and
    /// never enters history.
    public static let concealed = "org.nspasteboard.ConcealedType"
    public static let transient = "org.nspasteboard.TransientType"
    public static let autoGenerated = "org.nspasteboard.AutoGeneratedType"

    public static let privacy: Set<String> = [concealed, transient, autoGenerated]
}
