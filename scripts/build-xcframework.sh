#!/usr/bin/env bash
# Builds ctrl-core for macOS and iOS, generates the Swift bindings, and packages
# both as a Swift package at bindings/apple:
#
#   bindings/apple/
#     Package.swift
#     CtrlCoreFFI.xcframework     static libraries + C header
#     Sources/CtrlCore/CtrlCore.swift
#     Tests/CtrlCoreTests/          smoke test, run with `swift test`
#
# Usage: scripts/build-xcframework.sh [--macos-only]
set -euo pipefail
cd "$(dirname "$0")/.."

out=bindings/apple
targets=(aarch64-apple-darwin x86_64-apple-darwin)
if [[ "${1:-}" != "--macos-only" ]]; then
  targets+=(aarch64-apple-ios aarch64-apple-ios-sim)
fi

for t in "${targets[@]}"; do
  cargo build -p ctrl-core --release --target "$t"
done

rm -rf "$out/CtrlCoreFFI.xcframework" "$out/Sources" "$out/Tests" "$out/.build"
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

cargo run -q -p uniffi-bindgen -- generate \
  --library target/aarch64-apple-darwin/release/libctrl_core.dylib \
  --language swift --out-dir "$work/gen"

mkdir -p "$work/include" "$out/Sources/CtrlCore"
cp "$work/gen/CtrlCoreFFI.h" "$work/include/"
cp "$work/gen/CtrlCoreFFI.modulemap" "$work/include/module.modulemap"
cp "$work/gen/CtrlCore.swift" "$out/Sources/CtrlCore/CtrlCore.swift"
mkdir -p "$out/Tests/CtrlCoreTests"
cp tools/apple-smoke-test/SmokeTests.swift "$out/Tests/CtrlCoreTests/"

mkdir -p "$work/macos"
lipo -create \
  target/aarch64-apple-darwin/release/libctrl_core.a \
  target/x86_64-apple-darwin/release/libctrl_core.a \
  -output "$work/macos/libctrl_core.a"

args=(-library "$work/macos/libctrl_core.a" -headers "$work/include")
if [[ "${1:-}" != "--macos-only" ]]; then
  args+=(-library target/aarch64-apple-ios/release/libctrl_core.a -headers "$work/include")
  args+=(-library target/aarch64-apple-ios-sim/release/libctrl_core.a -headers "$work/include")
fi
xcodebuild -create-xcframework "${args[@]}" -output "$out/CtrlCoreFFI.xcframework"

cat > "$out/Package.swift" <<'SWIFT'
// swift-tools-version:6.0
// Generated by scripts/build-xcframework.sh. Do not edit.
import PackageDescription

let package = Package(
    name: "CtrlCore",
    platforms: [.macOS(.v15), .iOS(.v18)],
    products: [.library(name: "CtrlCore", targets: ["CtrlCore"])],
    targets: [
        .binaryTarget(name: "CtrlCoreFFI", path: "CtrlCoreFFI.xcframework"),
        .target(
            name: "CtrlCore",
            dependencies: ["CtrlCoreFFI"],
            linkerSettings: [.linkedFramework("SystemConfiguration")]
        ),
        .testTarget(name: "CtrlCoreTests", dependencies: ["CtrlCore"]),
    ],
    swiftLanguageModes: [.v5]
)
SWIFT

echo "Swift package written to $out"
